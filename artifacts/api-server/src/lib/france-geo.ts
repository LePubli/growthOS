export function departmentFromPostalCode(postalCode: string): string {
  if (/^97\d{3}$/.test(postalCode)) return postalCode.slice(0, 3);
  if (/^20\d{3}$/.test(postalCode)) return Number(postalCode.slice(0, 3)) <= 201 ? "2A" : "2B";
  return postalCode.slice(0, 2);
}
